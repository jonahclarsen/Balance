import { expect, test } from '@playwright/test'
import { openView } from '../helpers/navigation'

test('notes open and edit independently beside each other, including in IMAX', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'Side-by-side notes are desktop-only')
  test.setTimeout(90_000)
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await openView(page, 'Notes')
  await page.locator('.note-new').click()
  await page.getByRole('textbox', { name: 'Note title', exact: true }).fill('Reference')
  await page.locator('.note-new').click()
  const main = page.getByRole('region', { name: 'Main note', exact: true })
  const right = page.getByRole('region', { name: 'Right note', exact: true })
  await main.getByRole('textbox', { name: 'Note title', exact: true }).fill('Draft')

  const card = page.locator('.note-card-row').filter({ hasText: 'Reference' })
  const open = card.getByRole('button', { name: 'Open Reference on the right' })
  await expect(open).toHaveCSS('opacity', '0')
  await card.hover()
  await expect(open).toHaveCSS('opacity', '1')
  async function expectSplitBelowDate() {
    const dateBounds = await card.locator('time').boundingBox()
    const splitBounds = await open.boundingBox()
    expect(dateBounds).not.toBeNull()
    expect(splitBounds).not.toBeNull()
    expect(splitBounds!.y).toBeGreaterThan(dateBounds!.y + dateBounds!.height)
  }
  await expectSplitBelowDate()
  await open.click()
  await expectSplitBelowDate()
  await expect(main.getByRole('textbox', { name: 'Note title', exact: true })).toHaveValue('Draft')
  await expect(right.getByRole('textbox', { name: 'Note title', exact: true })).toHaveValue('Reference')
  await right.getByRole('textbox', { name: 'Note title', exact: true }).fill('Reference edited')
  // Title/body keyboard handoff must stay inside the right editor.
  await right.getByRole('textbox', { name: 'Note title', exact: true }).press('Enter')
  await page.keyboard.type('Saved in the right note')
  await expect(right.locator('.note-text')).toContainText('Saved in the right note')
  await expect(main.locator('.note-text')).not.toContainText('Saved in the right note')

  await page.getByRole('button', { name: 'Enter IMAX mode' }).click()
  await expect(main).toBeVisible()
  await expect(right).toBeVisible()
  const mainBounds = await main.boundingBox()
  const rightBounds = await right.boundingBox()
  expect(rightBounds!.x).toBeGreaterThanOrEqual(mainBounds!.x + mainBounds!.width - 1)
  await right.getByRole('button', { name: 'Close right note' }).click()
  await expect(right).toHaveCount(0)
  await expect(main.getByRole('textbox', { name: 'Note title', exact: true })).toHaveValue('Draft')
  await page.getByRole('button', { name: 'Exit IMAX mode' }).click()

  await page.locator('.note-card').filter({ hasText: 'Reference edited' }).click()
  await expect(main.locator('.note-text')).toContainText('Saved in the right note')
  await page.reload()
  await openView(page, 'Notes')
  await page.locator('.note-card').filter({ hasText: 'Reference edited' }).click()
  await expect(main.locator('.note-text')).toContainText('Saved in the right note')

  await page.locator('.note-card-row').filter({ hasText: 'Draft' }).hover()
  await page.getByRole('button', { name: 'Open Draft on the right' }).click()
  await expect(right).toBeVisible()
  await right.getByRole('button', { name: 'Bin it', exact: true }).click()
  await expect(right).toHaveCount(0)
  await expect(main.getByRole('textbox', { name: 'Note title', exact: true })).toHaveValue('Reference edited')

  await page.locator('.note-card-row').filter({ hasText: 'Reference edited' }).hover()
  await page.getByRole('button', { name: 'Open Reference edited on the right' }).click()
  await expect(right).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(right).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Open .* on the right/ })).toBeHidden()
})


test('mobile notes do not offer a side pane', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile', 'Mobile-only control check')
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await openView(page, 'Notes')
  await page.locator('.note-new').click()
  await expect(page.locator('.note-card')).toBeVisible()
  await expect(page.getByRole('button', { name: /Open .* on the right/ })).toBeHidden()
})

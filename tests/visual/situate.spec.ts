test('blocked targets can be added, edited, recategorized and removed', async ({page}) => {
  await page.getByRole('button',{name:'Edit Dolo',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Edit Dolo'})
  const table=dialog.getByRole('table',{name:'Blocked apps and websites'})
  await dialog.getByLabel('App ID or website to block').fill('com.example.chat')
  await expect(dialog.getByRole('group',{name:'Type'}).getByRole('button',{name:'App'})).toHaveAttribute('aria-pressed','true')
  const add=dialog.getByRole('button',{name:'Add',exact:true})
  await expect(add).toBeDisabled()
  await dialog.getByRole('group',{name:'Category'}).getByRole('button',{name:'Social',exact:true}).click()
  await add.click()
  await expect(dialog.getByRole('group',{name:'Category'}).getByRole('button',{name:'Social',exact:true})).toHaveAttribute('aria-pressed','false')
  await table.getByLabel('Edit com.example.chat').fill('com.example.messages')
  await table.getByLabel('Edit com.example.chat').press('Enter')
  const row=table.getByRole('row').filter({has:page.getByLabel('Edit com.example.messages')})
  await row.getByRole('button',{name:'Social',exact:true}).click()
  await row.getByRole('button',{name:'AI',exact:true}).click()
  await expect(row.getByRole('button',{name:'AI',exact:true})).toBeVisible()
  await table.getByRole('button',{name:'Remove reddit.com'}).click()
  await page.keyboard.press('Escape')
  await page.reload();await openView(page,'Situate')
  const targets=await page.evaluate(()=>JSON.parse(localStorage.getItem('balance-situate-v1')!).modes[0].targets)
  expect(targets.find((t:{value:string})=>t.value==='com.example.messages')).toMatchObject({kind:'app',category:'ai',id:'app:com.example.messages'})
  expect(targets.some((t:{value:string})=>t.value==='reddit.com')).toBe(false)
})

